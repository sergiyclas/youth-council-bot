from openai import OpenAI

from config import OPENAI_KEY

# Ініціалізація клієнта OpenAI
client = OpenAI(
    api_key=OPENAI_KEY  # Замість цього вставте ваш API-ключ
)

async def generate_post(client, event_info, max_length=750):
    """
    Генерує пост на основі переданої інформації з обмеженням на довжину.

    :param client: Ініціалізований клієнт OpenAI
    :param event_info: Текстова інформація про подію
    :param max_length: Максимальна довжина посту в символах (за замовчуванням 750)
    :return: Згенерований пост або повідомлення про помилку
    """
    prompt = f"""
        Ти — професійний копірайтер, який створює пости українською мовою для соціальних мереж у стилі Молодіжної ради при Рава-Руській міській раді. Завжди дотримуйся такого стилю та структури:
        - максимум 3 емодзі на пост!
        - офіційний стиль мовлення!
        - без хештегів і тегів!
        - обмеження в 700 символів на пост!
        
        1. Почни з короткого, але емоційного вступу. Наприклад:
           - Спершу що за подія, далі вказана дата і потім де воно відбулося і в рамках чого, якщо це присутнє.

        2. В основній частині:
           - Опиши подію (дата, місце, учасники).
           - Зроби текст структурованим, використовуючи маркери чи списки, але коротко. Наприклад:
             🔹 Сильні сторони, які нас об’єднують.
             🔹 Проблеми, над якими потрібно працювати.
           - Додай деталі про активності, ключові теми обговорення, внесок учасників.

        3. У заключній частині:
           - Вислови подяку організаторам, партнерам чи учасникам.
           - Додай натхненну фразу, яка мотивує долучитися до майбутніх подій.

        Напиши пост у цьому стилі. Використовуй чітке форматування і структурування тексту.
        
        Ось інформація для посту:
        {event_info}

    """
    # Розрахунок max_tokens для OpenAI (1 токен ≈ 4 символи)
    max_tokens = max_length

    try:
        # Виклик API для створення тексту
        completion = client.chat.completions.create(
            model="gpt-4",
            store=True,
            messages=[
                {"role": "user", "content": prompt}
            ],
            max_tokens=max_tokens
        )

        # Повертаємо згенерований текст
        return completion.choices[0].message.content

    except Exception as e:
        return f"Сталася помилка: {e}"